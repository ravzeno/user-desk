import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { writeFile } from "node:fs/promises";

// Generate from the same Nest and Better Auth documents used by user-service's docs.
const service = resolve(process.env.USER_SERVICE_DIR || "../user-service");
const require = createRequire(resolve(service, "package.json"));
require("dotenv").config({ path: resolve(service, ".env"), quiet: true });
require("reflect-metadata");
const { NestFactory } = require("@nestjs/core");
const { SwaggerModule, DocumentBuilder } = require("@nestjs/swagger");
const { AppModule } = await import(
  pathToFileURL(resolve(service, "dist/app.module.js")).href
);
const app = await NestFactory.create(AppModule, {
  logger: false,
  bodyParser: false,
});
let serviceDoc;
try {
  app.setGlobalPrefix("api");
  serviceDoc = SwaggerModule.createDocument(
    app,
    new DocumentBuilder().setTitle("User Service").setVersion("1").build(),
  );
} finally {
  await app.close();
}
const { auth } = await import(
  pathToFileURL(resolve(service, "dist/lib/auth.js")).href
);
const authDoc = await auth.api.generateOpenAPISchema();

function generatePaths(doc, prefix) {
  const entries = [];
  const seen = new Set();
  for (const [originalPath, operations] of Object.entries(doc.paths || {}).sort(
    ([a], [b]) => a.localeCompare(b),
  )) {
    for (const [method, operation] of Object.entries(operations)) {
      if (
        !["get", "post", "put", "patch", "delete", "options", "head"].includes(
          method,
        )
      )
        continue;
      const key = operation.operationId || `${method}_${originalPath}`;
      if (seen.has(key)) throw new Error(`Duplicate operationId: ${key}`);
      seen.add(key);
      const path =
        `${prefix}${originalPath}`.replace(/^\/api(?=\/|$)/, "") || "/";
      const params = [...path.matchAll(/\{([^}]+)\}/g)].map(
        (match) => match[1],
      );
      let value = JSON.stringify(path);
      if (params.length) {
        const type = params
          .map((name) => `${JSON.stringify(name)}: string | number`)
          .join("; ");
        const parts = path
          .split(/(\{[^}]+\})/g)
          .map((part) =>
            /^\{[^}]+\}$/.test(part)
              ? `encodeURIComponent(String(params[${JSON.stringify(part.slice(1, -1))}]))`
              : JSON.stringify(part),
          );
        value = `(params: { ${type} }) => ${parts.join(" + ")}`;
      }
      entries.push(
        `  /** ${method.toUpperCase()} ${prefix}${originalPath} */\n  ${JSON.stringify(key)}: ${value},`,
      );
    }
  }
  return entries.join("\n");
}
const output = `// Generated by npm run generate:api. Do not edit by hand.\n// Paths are relative to VITE_API_BASE_URL (which includes /api).\nexport const servicePaths = {\n${generatePaths(serviceDoc, "")}\n} as const;\n\nexport const authPaths = {\n${generatePaths(authDoc, "/api/auth")}\n} as const;\n`;
await writeFile(
  new URL("../src/lib/api/generated/paths.ts", import.meta.url),
  output,
);
console.log("Generated src/lib/api/generated/paths.ts");
